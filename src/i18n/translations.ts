export const translations: Record<Lang, Dict> = {
  en,
  zh_cn,
  zh_tw,
  ja,
  ko,
  de,
  es,
  fr,
  pt_br,
  ru,
};

/// Map a raw locale string (e.g. "zh_CN", "ja-JP") to a supported Lang code.
/// Returns "en" for unsupported languages.
export function resolveLang(locale: string): Lang {
  if (!locale) return "en";
  const lower = locale.toLowerCase().replace(/[_-]/g, "_");

  // Direct match
  if (lower in translations) return lower as Lang;

  // Try just the language part
  const lang = lower.split("_")[0];
  if (lang === "zh") {
    if (lower.includes("tw") || lower.includes("hant")) return "zh_tw";
    return "zh_cn";
  }
  if (lang === "pt") return "pt_br";
  if (lang in translations) return lang as Lang;

  return "en";
}
